type Schema = Record<string, unknown>
// Every keyword here is shown on the page (description in its own column); any other keyword is an error.
const SCHEMA_KEYS = new Set(['type', 'description', 'minimum', 'maximum', 'anyOf', 'items', 'minItems', 'maxItems', 'enum',
  'properties', 'required', 'minLength', 'maxLength', 'pattern', 'default'])

/** A short type for a JSON-schema argument; an unknown schema keyword is an error so the page never drops a constraint. */
export function typeName(s: Schema, where: string): string {
  for (const k of Object.keys(s)) if (!SCHEMA_KEYS.has(k)) throw new Error(`${where}: schema keyword "${k}" isn't handled by the docs generator`)
  let t: string
  if (Array.isArray(s.anyOf)) t = (s.anyOf as Schema[]).map((x, i) => typeName(x, `${where}.anyOf[${i}]`)).join(' \\| ')
  else if (Array.isArray(s.enum)) t = (s.enum as unknown[]).map((v) => JSON.stringify(v)).join(' \\| ')
  else if (Array.isArray(s.type)) t = (s.type as string[]).join(' \\| ')
  else if (s.type === 'array') t = `${typeName((s.items ?? {}) as Schema, `${where}[]`)}[]`
  else if (s.type === 'object' && s.properties) {
    const props = s.properties as Record<string, Schema>
    const req = new Set((s.required as string[] | undefined) ?? [])
    const keys = Object.keys(props)
    t = keys.length <= 4 ? `{ ${keys.map((k) => (req.has(k) ? k : `${k}?`)).join(', ')} }` : 'object'
  } else if (typeof s.type === 'string') t = s.type
  else throw new Error(`${where}: no type`)
  const range = [s.minimum !== undefined ? `≥ ${s.minimum}` : '', s.maximum !== undefined ? `≤ ${s.maximum}` : ''].filter(Boolean)
  if (s.minItems !== undefined) range.push(`at least ${s.minItems}`)
  if (s.maxItems !== undefined) range.push(`at most ${s.maxItems}`)
  if (s.minLength !== undefined) range.push(`length ≥ ${s.minLength}`)
  if (s.maxLength !== undefined) range.push(`length ≤ ${s.maxLength}`)
  if (s.pattern !== undefined) range.push(`matches ${code(String(s.pattern))}`)
  if (s.default !== undefined) range.push(`default ${code(JSON.stringify(s.default))}`)
  return range.length ? `${t} (${range.join(', ')})` : t
}

function mcpPage(): string {
  const tools = agentTools()
  const parts = [
    'The tools the `ai-task-tracking` MCP server lists to agents, as `tools/list` sends them: the title, the hints, the',
    'description and the arguments. Agents call them as `mcp__ai-task-tracking__<name>`.',
    '',
    table(['Tool', 'Title', 'Kind'], tools.map((t) => [`[${code(t.name)}](#${t.name})`, cell(t.annotations.title), t.annotations.readOnlyHint ? 'read' : 'write'])),
  ]
  for (const t of tools) {
    const a = t.annotations
    const hints = [
      a.readOnlyHint ? '`readOnlyHint`' : '',
      a.destructiveHint === false ? '`destructiveHint: false`' : '',
      a.idempotentHint ? '`idempotentHint`' : '',
      a.openWorldHint === false ? '`openWorldHint: false`' : '',
    ].filter(Boolean)
    parts.push('', `## ${t.name}`, '', `**${prose(a.title)}** · ${a.readOnlyHint ? 'read-only' : 'write'} · hints: ${hints.join(', ')}`, '', prose(t.description))
    const schema = t.inputSchema as Schema
    const props = (schema.properties ?? {}) as Record<string, Schema>
    const req = new Set((schema.required as string[] | undefined) ?? [])
    const names = Object.keys(props)
    if (!names.length) { parts.push('', 'No arguments.'); continue }
    parts.push('', table(['Argument', 'Type', 'Required', 'Description'], names.map((n) => {
      const p = props[n]!
      return [code(n), typeName(p, `${t.name}.${n}`).replace(/</g, '&lt;'), req.has(n) ? 'yes' : '', cell(typeof p.description === 'string' ? p.description : '')]
    })))
  }
  return page({
    title: 'MCP tools',
    description: 'Every tool the ai-task-tracking MCP server gives agents, with its hints and arguments.',
    order: 3,
    source: ['src/mcp/surface.ts (agentTools)', 'src/tools/schemas.ts'],
    body: parts.join('\n'),
  })
}

