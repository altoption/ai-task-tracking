const SCRIPTS = [
  { path: 'install.sh', title: 'install.sh (users)', intro: 'The user installer at the repo root. Piped from `curl`, or `./install.sh` from a clone.' },
  { path: 'uninstall.sh', title: 'uninstall.sh (users)', intro: 'The user uninstaller at the repo root. It runs `aitt uninstall` from the installed app.' },
  { path: 'scripts/install.sh', title: 'scripts/install.sh (developers)', intro: 'The developer installer: rebuilds this checkout into the app folder.' },
]

/** The `usage()` heredoc of a shell script, read as text. */
export function shellUsage(src: string, path: string): string {
  const m = /usage\(\) \{\n\s*cat <<'USAGE'\n([\s\S]*?)\nUSAGE\n/.exec(src)
  if (!m) throw new Error(`${path}: no usage() heredoc (cat <<'USAGE' … USAGE)`)
  return m[1]!
}

/** Long flags the script's argument `case` accepts (not --help, short aliases or lines marked as a test hook). */
function caseFlags(src: string): Set<string> {
  const out = new Set<string>()
  for (const line of src.split('\n')) {
    const m = /^\s+((?:-{1,2}[\w-]+)(?:\s*\|\s*-{1,2}[\w-]+)*)\)/.exec(line)
    if (!m || /test hook/.test(line)) continue
    for (const f of m[1]!.split('|').map((x) => x.trim())) if (f.startsWith('--') && f !== '--help') out.add(f)
  }
  return out
}

async function installersPage(): Promise<string> {
  const parts = ['The installers\' own `--help` text, and the options and environment variables it lists.']
  for (const s of SCRIPTS) {
    const src = await readFile(join(ROOT, s.path), 'utf8')
    const usage = shellUsage(src, s.path)
    const documented = mentionedFlags(usage)
    const undocumented = [...caseFlags(src)].filter((f) => !documented.has(f))
    if (undocumented.length) throw new Error(`${s.path}: accepts ${undocumented.join(', ')} but its usage text doesn't mention it`)
    parts.push('', `## ${s.title}`, '', s.intro, '', fence(usage))
    const flags = parseOptions(usage, 'flag'), env = parseOptions(usage, 'env')
    if (flags.length) {
      const inTable = new Set(flags.flatMap((o) => [...mentionedFlags(o.names)]))
      const missing = [...caseFlags(src)].filter((f) => !inTable.has(f))
      if (missing.length) throw new Error(`${s.path}: ${missing.join(', ')} not parsed from the usage text's option lines`)
    }
    if (flags.length) parts.push('', '### Options', '', optionTable(flags, 'Option'))
    if (env.length) parts.push('', '### Environment', '', optionTable(env, 'Variable'))
  }
  return page({
    title: 'Installer flags',
    description: 'The options and environment of install.sh, uninstall.sh and scripts/install.sh, from their --help text.',
    order: 2,
    source: SCRIPTS.map((s) => s.path),
    body: parts.join('\n'),
  })
}

