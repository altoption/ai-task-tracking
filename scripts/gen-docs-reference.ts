/** Every command in the top-level help, and the detailed usage it has (null: the top-level line is all there is). */
const COMMAND_USAGE: Record<string, string | null> = {
  serve: null,
  mcp: null,
  setup: SETUP_USAGE,
  open: OPEN_USAGE,
  docs: DOCS_USAGE,
  guidance: GUIDANCE_USAGE,
  uninstall: UNINSTALL_USAGE,
  bench: BENCH_USAGE,
}

function cliPage(): string {
  const commands = USAGE.split('\n').slice(1).map((line) => {
    const m = /^ {2}(\S+)((?: <[^>]+>)?)\s{2,}(\S.*)$/.exec(line)
    if (!m) throw new Error(`top-level usage: can't parse the line "${line}"`)
    return { name: m[1]!, args: m[2]!.trim(), summary: m[3]! }
  })
  const listed = new Set(commands.map((c) => c.name))
  for (const name of Object.keys(COMMAND_USAGE)) if (!listed.has(name)) throw new Error(`aitt ${name} has a usage text but isn't in the top-level help`)
  for (const c of commands) if (!(c.name in COMMAND_USAGE)) throw new Error(`aitt ${c.name} is new: add it to COMMAND_USAGE in scripts/gen-docs-reference.ts`)

  const parts = [
    '`aitt` is the command-line tool inside the app (`~/.local/bin/aitt` links to it). `aitt` with no command prints:',
    '',
    fence(USAGE),
  ]
  for (const c of commands) {
    const usage = COMMAND_USAGE[c.name]
    parts.push('', `## aitt ${c.name}`, '', `${prose(c.summary.charAt(0).toUpperCase() + c.summary.slice(1))}.`)
    if (usage) {
      parts.push('', fence(usage))
      const opts = parseOptions(usage, 'flag')
      if (opts.length) parts.push('', optionTable(opts, 'Flag'))
    } else {
      parts.push('', fence(`aitt ${c.name}${c.args ? ' ' + c.args : ''}`, 'sh'))
    }
  }
  return page({
    title: 'CLI',
    description: 'Every aitt command with its usage and flags, from the help texts the CLI prints.',
    order: 1,
    source: ['src/cli/usage.ts', 'src/setup/setup.ts', 'src/setup/uninstall.ts', 'src/cli/open.ts'],
    body: parts.join('\n'),
  })
}

