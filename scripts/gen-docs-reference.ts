/**
 * Writes the docs site's reference pages (site/src/content/docs/reference/) from the sources they describe:
 * the CLI's usage strings, the installers' --help text, the MCP tool list agents get, the app's Settings and the
 * config.yml defaults. Nothing is run; sources are imported or read as text.
 *
 *   bun scripts/gen-docs-reference.ts           write the pages (bun run docs:gen)
 *   bun scripts/gen-docs-reference.ts --check   exit 1 when the committed pages differ (tests/docs-reference.test.ts)
 *
 * A source that no longer parses the way this script expects is an error, never a silently thinner page.
 */
