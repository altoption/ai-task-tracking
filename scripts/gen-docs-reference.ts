// ---------- markdown helpers ----------

/** Escapes text for Markdown prose: HTML-significant characters outside `code spans` (inside them they are literal). */
function prose(s: string): string {
  return s.split(/(`[^`]*`)/).map((part, i) => (i % 2 ? part : part.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;'))).join('')
}
/** Prose for a table cell: no pipes or line breaks. */
function cell(s: string): string {
  return prose(s).replace(/\|/g, '\\|').replace(/\n+/g, '<br>')
}
function code(s: string): string {
  return '`' + s + '`'
}
function fence(text: string, lang = 'text'): string {
  if (text.includes('```')) throw new Error('usage text contains a code fence')
  return '```' + lang + '\n' + text.replace(/\s+$/, '') + '\n```'
}
function table(head: string[], rows: string[][]): string {
  return [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n')
}
function page(o: { title: string; description: string; order: number; source: string[]; body: string }): string {
  return [
    '---',
    `title: ${JSON.stringify(o.title)}`,
    `description: ${JSON.stringify(o.description)}`,
    'sidebar:',
    `  order: ${o.order}`,
    '---',
    '',
    MARK_COMMENT,
    '',
    `:::note[Generated]`,
    `${MARK} Source: ${o.source.map(code).join(', ')}.`,
    ':::',
    '',
    o.body.replace(/\s+$/, ''),
    '',
  ].join('\n')
}

// ---------- usage-text parsing (CLI and shell scripts share the format) ----------

interface Opt { names: string; text: string }

/**
 * Option lines in a help text: two spaces, the option (`--yes, -y`, `--home <dir>`, `AITT_HOME=<dir>`), spaces, the
 * text; deeper-indented lines continue the text.
 */
export function parseOptions(usage: string, kind: 'flag' | 'env'): Opt[] {
  const head = kind === 'flag'
    ? /^ {2}(-{1,2}[A-Za-z][\w-]*(?:, -{1,2}[A-Za-z][\w-]*)*(?: <[^>]+>)?)\s+(\S.*)$/
    : /^ {2}([A-Z][A-Z_]*=\S*)\s+(\S.*)$/
  const out: Opt[] = []
  let last: Opt | undefined
  for (const line of usage.split('\n')) {
    const m = head.exec(line)
    if (m) { last = { names: m[1]!.trim(), text: m[2]!.trim() }; out.push(last); continue }
    if (last && /^ {4,}\S/.test(line) && !/^ {2}\S/.test(line)) { last.text += ' ' + line.trim(); continue }
    last = undefined
  }
  return out
}

function optionTable(opts: Opt[], head: string): string {
  return table([head, 'What it does'], opts.map((o) => [code(o.names), cell(o.text)]))
}

/** Flags anywhere in a text (`--yes`, `-y`). */
function mentionedFlags(text: string): Set<string> {
  return new Set([...text.matchAll(/(?<![\w-])(--?[a-z][\w-]*)/g)].map((m) => m[1]!))
}

