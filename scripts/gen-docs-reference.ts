/** File name → content of every generated page. */
export async function generate(): Promise<Record<string, string>> {
  return {
    'cli.md': cliPage(),
    'installers.md': await installersPage(),
    'mcp-tools.md': mcpPage(),
    'settings.md': await settingsPage(),
    'config.md': configPage(),
  }
}

/** Differences between the committed pages and what generate() writes; empty when they match. */
export async function check(): Promise<string[]> {
  const want = await generate()
  const have = new Set(await readdir(OUT_DIR).catch(() => [] as string[]))
  const out: string[] = []
  for (const [name, text] of Object.entries(want)) {
    if (!have.has(name)) { out.push(`${name}: missing`); continue }
    if ((await readFile(join(OUT_DIR, name), 'utf8')) !== text) out.push(`${name}: out of date`)
  }
  for (const name of have) if (!(name in want)) out.push(`${name}: not generated (remove it, or add it to the generator)`)
  return out
}

if (import.meta.main) {
  if (process.argv.includes('--check')) {
    const diffs = await check()
    if (diffs.length) {
      console.error(`Reference pages are out of date; run \`bun run docs:gen\`:\n  ${diffs.join('\n  ')}`)
      process.exit(1)
    }
    console.log('Reference pages are up to date.')
  } else {
    const pages = await generate()
    await mkdir(OUT_DIR, { recursive: true })
    for (const name of await readdir(OUT_DIR)) if (!(name in pages)) await rm(join(OUT_DIR, name))
    for (const [name, text] of Object.entries(pages)) await writeFile(join(OUT_DIR, name), text)
    console.log(`Wrote ${Object.keys(pages).length} pages to site/src/content/docs/reference/`)
  }
}
